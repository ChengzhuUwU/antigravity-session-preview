let currentLang = (typeof localStorage !== 'undefined' && localStorage.getItem('amp-lang')) || 'en';
if (!MESSAGES[currentLang]) currentLang = 'en';

export function getLang() {
  return currentLang;
}

export function setLang(lang) {
  currentLang = MESSAGES[lang] ? lang : 'en';
  if (typeof localStorage !== 'undefined') {
    localStorage.setItem('amp-lang', currentLang);
  }
  if (typeof document !== 'undefined') {
    document.documentElement.setAttribute('lang', currentLang === 'zh' ? 'zh-CN' : 'en');
  }
  return currentLang;
}

export function t(key, vars = null) {
  const dict = MESSAGES[currentLang] || MESSAGES.en;
  let str = dict[key] ?? MESSAGES.en[key] ?? key;
  if (vars && typeof str === 'string') {
    for (const [k, v] of Object.entries(vars)) {
      str = str.replaceAll(`{${k}}`, String(v ?? ''));
    }
  }
  return str;
}

export function applyStaticI18n(root = typeof document !== 'undefined' ? document : null) {
  if (!root) return;
  root.querySelectorAll('[data-i18n]').forEach((node) => {
    node.textContent = t(node.dataset.i18n);
  });
  root.querySelectorAll('[data-i18n-html]').forEach((node) => {
    node.innerHTML = t(node.dataset.i18nHtml);
  });
  root.querySelectorAll('[data-i18n-title]').forEach((node) => {
    node.title = t(node.dataset.i18nTitle);
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((node) => {
    node.placeholder = t(node.dataset.i18nPlaceholder);
  });
}
